/** Every curated reference as { book, chapter, verse }. */
export const DAILY_VERSES = Object.entries(LIST).flatMap(([book, refs]) =>
  refs.split(" ").map((r) => { const [chapter, verse] = r.split(":").map(Number); return { book, chapter, verse }; }));

// A fixed stride that shares no factor with the list length walks the whole
// list before repeating and keeps neighbouring days in different books.
const STRIDE = 211;

/** The reference for a calendar day (local time). Same date → same verse, on every device. */
export function verseOfTheDay(date = new Date()) {
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return DAILY_VERSES[(day * STRIDE) % DAILY_VERSES.length];
}
